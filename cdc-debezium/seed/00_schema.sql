-- Camada 3: esquema do banco de origem (Postgres/Neon).
-- Dados sintéticos de um domínio de pagamentos. Executar como o usuário admin do Neon.
-- PII: customers.full_name, email, phone. PCI: cards.last4 (só os 4 últimos dígitos, nunca o número).

DROP TABLE IF EXISTS transactions, cards, accounts, merchants, customers CASCADE;

CREATE TABLE customers (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   TEXT        NOT NULL,
  email       TEXT        NOT NULL,
  phone       TEXT,
  city        TEXT,
  created_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE accounts (
  account_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  BIGINT        NOT NULL REFERENCES customers(customer_id),
  account_type TEXT          NOT NULL CHECK (account_type IN ('CHECKING','SAVINGS')),
  balance      NUMERIC(15,2) NOT NULL,
  status       TEXT          NOT NULL CHECK (status IN ('ACTIVE','BLOCKED')),
  opened_at    TIMESTAMPTZ   NOT NULL
);

CREATE TABLE cards (
  card_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES accounts(account_id),
  brand      TEXT   NOT NULL CHECK (brand IN ('VISA','MASTERCARD','ELO')),
  last4      CHAR(4) NOT NULL,
  status     TEXT   NOT NULL CHECK (status IN ('ACTIVE','BLOCKED')),
  expires_at DATE   NOT NULL
);

CREATE TABLE merchants (
  merchant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  category    TEXT NOT NULL,
  country     CHAR(2) NOT NULL
);

CREATE TABLE transactions (
  transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id        BIGINT        NOT NULL REFERENCES cards(card_id),
  account_id     BIGINT        NOT NULL REFERENCES accounts(account_id),
  merchant_id    BIGINT        NOT NULL REFERENCES merchants(merchant_id),
  amount         NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  currency       CHAR(3)       NOT NULL,
  status         TEXT          NOT NULL CHECK (status IN ('APPROVED','DECLINED')),
  created_at     TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_tx_card_time ON transactions (card_id, created_at);

-- Para o CDC: UPDATE e DELETE trazem a linha INTEIRA em "before" (custo: mais WAL).
ALTER TABLE customers    REPLICA IDENTITY FULL;
ALTER TABLE accounts     REPLICA IDENTITY FULL;
ALTER TABLE cards        REPLICA IDENTITY FULL;
ALTER TABLE merchants    REPLICA IDENTITY FULL;
ALTER TABLE transactions REPLICA IDENTITY FULL;
